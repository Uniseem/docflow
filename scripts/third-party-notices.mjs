/**
 * @param {string} dir
 * @returns {string | undefined}
 */
function findLicenseFile(dir) {
  if (!existsSync(dir)) return undefined
  const names = readdirSync(dir)
  const match = names.find((name) => /^licen[cs]e/i.test(name) || /^copying$/i.test(name))
  return match ? join(dir, match) : undefined
}

/**
 * @param {string} name
 * @returns {{ license: string, text: string }}
 */
function readPackageLicense(name) {
  const dir = join(root, 'node_modules', ...name.split('/'))
  const pkgPath = join(dir, 'package.json')
  if (!existsSync(pkgPath)) {
    return { license: 'UNKNOWN', text: `(package not installed: ${name})` }
  }
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  const license = typeof pkg.license === 'string' ? pkg.license : 'UNKNOWN'
  const licenseFile = findLicenseFile(dir)
  const text = licenseFile
    ? readFileSync(licenseFile, 'utf8').trim()
    : `(no LICENSE file in ${name})`
  return { license, text }
}

// Packages that npm installs but electron-builder.yml keeps out of the app
// (`!**/node_modules/@napi-rs/**`: pdf.js's optional native canvas, see ADR-0010).
const NOT_SHIPPED_PREFIXES = ['@napi-rs/']

/** @param {string} name */
function isShipped(name) {
  return !NOT_SHIPPED_PREFIXES.some((prefix) => name.startsWith(prefix))
}

function productionPackageNames() {
  const lockPath = join(root, 'package-lock.json')
  if (!existsSync(lockPath)) return []
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const direct = new Set(Object.keys(pkg.dependencies ?? {}))
  /** @type {Set<string>} */
  const names = new Set(direct)
  const packages = lock.packages ?? {}
  for (const [key, value] of Object.entries(packages)) {
    if (value.dev) continue
    if (!key.startsWith('node_modules/')) continue
    const name = key.slice('node_modules/'.length)
    if (name.includes('node_modules/')) continue
    // Optional platform binaries for other OSes/CPUs are never installed, so never shipped.
    if (value.optional && !existsSync(join(root, key, 'package.json'))) continue
    names.add(name)
  }
  return [...names].filter(isShipped).sort()
}

const bundled = JSON.parse(readFileSync(join(root, 'scripts/bundled-deps.json'), 'utf8'))
const sections = []

sections.push('## Production dependencies\n')
for (const name of productionPackageNames()) {
  const { license, text } = readPackageLicense(name)
  sections.push(`### ${name} (${license})\n\n${text}\n`)
}

sections.push('## Bundled renderer dependencies\n')
for (const name of bundled) {
  const { license, text } = readPackageLicense(name)
  sections.push(`### ${name} (${license})\n\n${text}\n`)
}

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), `${preamble}${sections.join('\n')}`)
